-- =====================================================
-- Pizza Sales Mini Project - MySQL
-- Schema + Sample Data + Analysis Queries
-- =====================================================

DROP DATABASE IF EXISTS pizza_sales;
CREATE DATABASE pizza_sales;
USE pizza_sales;

-- ---------------------------------------------------
-- 1. Schema
-- ---------------------------------------------------

CREATE TABLE pizza_types (
    pizza_type_id VARCHAR(20) PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    category      VARCHAR(20)  NOT NULL,
    ingredients   VARCHAR(300)
);

CREATE TABLE pizzas (
    pizza_id      VARCHAR(20) PRIMARY KEY,
    pizza_type_id VARCHAR(20) NOT NULL,
    size          VARCHAR(5)  NOT NULL,
    price         DECIMAL(6,2) NOT NULL,
    FOREIGN KEY (pizza_type_id) REFERENCES pizza_types(pizza_type_id)
);

CREATE TABLE orders (
    order_id   INT PRIMARY KEY AUTO_INCREMENT,
    order_date DATE NOT NULL,
    order_time TIME NOT NULL
);

CREATE TABLE order_details (
    order_details_id INT PRIMARY KEY AUTO_INCREMENT,
    order_id  INT NOT NULL,
    pizza_id  VARCHAR(20) NOT NULL,
    quantity  INT NOT NULL,
    FOREIGN KEY (order_id) REFERENCES orders(order_id),
    FOREIGN KEY (pizza_id) REFERENCES pizzas(pizza_id)
);

